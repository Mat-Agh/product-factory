//! Generate provider-specific agent definitions from the kit's canonical roles.

use std::fs;
use std::path::{Path, PathBuf};

use crate::{descriptor::Descriptor, discovery, install};

const MARK: &str = "# Generated by Product Factory. Configure routing in .factory/factory.yaml.";
const CODEX_SKILL: &str = ".agents/skills/product-factory/SKILL.md";
const SKILL_MARK: &str = "<!-- Installed by Product Factory. -->";

pub(crate) fn field<'a>(frontmatter: &'a str, key: &str) -> Result<&'a str, String> {
    frontmatter
        .lines()
        .filter_map(|line| line.split_once(": "))
        .find_map(|(k, v)| (k == key).then_some(v))
        .ok_or_else(|| format!("Factory role is missing {key}"))
}

pub struct Role {
    pub filename: PathBuf,
    pub claude: String,
    pub codex: String,
    pub antigravity: String,
}

pub fn roles(factory: &Path, d: &Descriptor) -> Result<Vec<Role>, String> {
    install::agent_files(factory)
        .into_iter()
        .map(|path| {
            let text = fs::read_to_string(&path).map_err(|e| e.to_string())?;
            let (front, body) = text
                .strip_prefix("---\n")
                .and_then(|s| s.split_once("\n---\n"))
                .ok_or_else(|| format!("Invalid frontmatter in {}", path.display()))?;
            let native_model = field(front, "model")?;
            let tier = match native_model {
                "opus" => "deep",
                "sonnet" => "build",
                other => return Err(format!("Unknown model tier {other} in {}", path.display())),
            };
            let model = d.get(&format!("models.{tier}")).unwrap_or(native_model);
            if !model.bytes().all(|b| b.is_ascii_alphanumeric() || b"-_.:/@".contains(&b)) {
                return Err(format!("Invalid Claude model ID in models.{tier}"));
            }
            let name = field(front, "name")?;
            let desc = field(front, "description")?;
            let effort = field(front, "effort")?;
            let claude = text.replacen(&format!("\nmodel: {native_model}\n"), &format!("\nmodel: {model}\n"), 1);

            // JSON quoting for these strings is compatible with TOML basic strings.
            let quoted = |s: &str| serde_json::Value::String(s.into()).to_string();
            let instructions = format!(
                "Read the installed Factory protocol and constitution at the paths supplied by the coordinator, then read the target checkout’s AGENTS.md and the owning module’s instructions. Follow the role’s artifact and scope restrictions. For code navigation, follow the protocol’s Graphify instructions.\n{body}"
            );
            let mut codex = format!(
                "{MARK}\nname = {}\ndescription = {}\nmodel_reasoning_effort = {}\ndeveloper_instructions = {}\n",
                quoted(&format!("factory-{name}")),
                quoted(desc),
                quoted(effort),
                quoted(&instructions),
            );
            if let Some(model) = d.get(&format!("models.codex_{tier}")) {
                codex.push_str(&format!("model = {}\n", quoted(model)));
            }
            let google_model = if tier == "deep" { "pro" } else { "flash" };
            let antigravity = format!(
                "---\nname: factory-{name}\ndescription: {}\nmodel: {google_model}\nmainAgent: false\nsubagent: true\ntools: [view_file, grep_search, run_command, replace_file_content]\n---\n{SKILL_MARK}\n{instructions}\n",
                quoted(desc)
            );
            Ok(Role {
                filename: path.file_name().unwrap().into(),
                claude,
                codex,
                antigravity,
            })
        })
        .collect()
}

fn files(factory: &Path, roles: &[Role]) -> Result<Vec<(PathBuf, String, &'static str)>, String> {
    let mut files = vec![(
        PathBuf::from(CODEX_SKILL),
        format!(
            "{}\n{SKILL_MARK}\n",
            fs::read_to_string(factory.join("kit").join(CODEX_SKILL)).map_err(|e| e.to_string())?
        ),
        SKILL_MARK,
    )];
    for role in roles {
        files.push((
            Path::new(".codex/agents").join(format!(
                "factory-{}",
                role.filename.with_extension("toml").display()
            )),
            role.codex.clone(),
            MARK,
        ));
        files.push((
            Path::new(".agents/agents").join(format!("factory-{}", role.filename.display())),
            role.antigravity.clone(),
            SKILL_MARK,
        ));
    }
    Ok(files)
}

pub fn install_shared(factory: &Path, root: &Path, roles: &[Role]) -> Result<(), String> {
    let files = files(factory, roles)?;
    for (relative, _, marker) in &files {
        let path = root.join(relative);
        if !discovery::local_path(root, relative)
            || (path.exists()
                && !fs::read_to_string(&path).is_ok_and(|s| s.lines().any(|line| line == *marker)))
        {
            return Err(format!(
                "Conflicting Factory runtime file at {}; review it before installing",
                path.display()
            ));
        }
    }
    for (relative, text, _) in files {
        let path = root.join(relative);
        fs::create_dir_all(path.parent().unwrap()).map_err(|e| e.to_string())?;
        if fs::read_to_string(&path).ok().as_deref() != Some(&text) {
            fs::write(path, text).map_err(|e| e.to_string())?;
        }
    }
    Ok(())
}

pub fn stale_shared(factory: &Path, root: &Path, d: &Descriptor) -> Result<Vec<PathBuf>, String> {
    let roles = roles(factory, d)?;
    Ok(files(factory, &roles)?
        .into_iter()
        .filter_map(|(path, text, _)| {
            (fs::read_to_string(root.join(&path)).ok().as_deref() != Some(&text)).then_some(path)
        })
        .collect())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn model_overrides_follow_role_tiers() {
        let factory = Path::new(env!("CARGO_MANIFEST_DIR")).parent().unwrap();
        let d =
            crate::descriptor::parse("models:\n  deep: custom-claude\n  codex_build: custom-gpt\n");
        let roles = roles(factory, &d).unwrap();
        let find = |name| {
            roles
                .iter()
                .find(|r| r.filename == Path::new(name))
                .unwrap()
        };
        let deep = find("tech-lead.md");
        assert!(deep.claude.contains("model: custom-claude\neffort: high"));
        assert!(deep.codex.contains("model_reasoning_effort = \"high\""));
        assert!(!deep.codex.contains("\nmodel = "));
        let build = find("engineer.md");
        assert!(build.claude.contains("model: sonnet\neffort: medium"));
        assert!(build.codex.contains("model_reasoning_effort = \"medium\""));
        assert!(build.codex.contains("model = \"custom-gpt\""));
    }
}
